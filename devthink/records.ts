/**
 * records.ts — the shared record infrastructure of the gate evidence
 * modules: the flat folder law dissolved the devthink/artifacts folder of the
 * application first layer, so every gate records its evidence as one typed
 * const committed inside its own module (the same doctrine the permbaseline
 * module carries) instead of writing a json artifact at run time. This module
 * owns the three pieces every gate shares:
 *
 * - the record renderer: one fresh report becomes the dense committed record
 *   text (JSON.stringify shape, quoted keys) so the committed record and the
 *   regenerated record never drift in shape;
 * - the sync pass: the gate rewrites the record const inside its own module
 *   file (the block between the `export const <name>:` line and its closing
 *   `};` at column zero), so a release refresh rides one reviewable commit —
 *   the same contract the permdiff sync owns for its baseline module;
 * - the summary math: the {total, passed, failed} invariants every recorded
 *   summary answers, so a hand-edited record never passes as a recorded run.
 *
 * The gates keep their run-verify contract: the default mode runs the suite,
 * logs every entry and exits nonzero on any failure while it verifies the
 * committed record stays internally consistent; the sync mode re-runs the
 * suite and rewrites the record the same run produced, printing the fresh
 * record as the final stdout line so the lanes that refresh the evidence
 * parse it without reading the module back.
 */
import { readFile, writeFile } from "node:fs/promises";

/** The outcome summary shape most gate records carry: the total count of
 * recorded entries, the passing share and the failing share. */
export interface recordsummary {
  total: number;
  passed: number;
  failed: number;
}

/** Renders one fresh report as the committed record const text: the dense
 * JSON.stringify shape with quoted keys, typed by the record interface the
 * gate declares, so the committed bytes and the regenerated bytes stay
 * byte identical for the deterministic reports. */
export function renderrecord(recordname: string, recordtype: string, record: unknown): string {
  return `export const ${recordname}: ${recordtype} = ${JSON.stringify(record, null, 2)};`;
}

/** Rewrites the record const inside the gate's own module file: the block
 * between the `export const <recordname>:` declaration and its closing `};`
 * at column zero — the rendered record never places a column-zero `};`
 * inside its body, so the splice stays exact. Answers the fresh record
 * serialized, the line the sync mode prints last. */
export async function syncrecord(options: {
  /** the module url of the gate itself (import.meta.url) */
  moduleurl: string;
  /** the exported const name of the record */
  recordname: string;
  /** the type name the record declares */
  recordtype: string;
  /** the fresh report the run produced */
  record: unknown;
}): Promise<string> {
  const modulepath = new URL(options.moduleurl);
  const source = await readFile(modulepath, "utf8");
  const opening = `export const ${options.recordname}:`;
  const start = source.indexOf(opening);
  if (start === -1)
    throw new Error(`The record const ${options.recordname} sits absent from its own module; the sync refuses to guess.`);
  const end = source.indexOf("\n};", start);
  if (end === -1)
    throw new Error(`The record const ${options.recordname} carries no closing block; the sync refuses to guess.`);
  const fresh = renderrecord(options.recordname, options.recordtype, options.record);
  const updated = `${source.slice(0, start)}${fresh}${source.slice(end + 3)}`;
  await writeFile(modulepath, updated, "utf8");
  return JSON.stringify(options.record);
}

/** Verifies the {total, passed, failed} math of one recorded summary and
 * answers the problem list (empty when the record stays consistent): the
 * total equals the passed plus the failed share and neither count turns
 * negative — the invariants every recorded run answers whatever its scale. */
export function summaryproblemsof(summary: recordsummary): string[] {
  const problems: string[] = [];
  if (summary.total !== summary.passed + summary.failed)
    problems.push(`the summary records ${summary.total} entries while ${summary.passed} passed and ${summary.failed} failed`);
  if (summary.passed < 0 || summary.failed < 0 || summary.total < 0)
    problems.push("the summary carries a negative count");
  return problems;
}

/** Reads the sync argument off the command line: the gates answer `sync` as
 * their second positional so `node ../tests/devthink.agentcert.ts sync`
 * refreshes the committed record the same run produces. */
export function syncmode(): boolean {
  return process.argv[2] === "sync";
}
