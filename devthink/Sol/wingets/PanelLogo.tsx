type SolLogoMarkProps = {
  /** rendered square size in px */
  size?: number;
  /** accessible name; omit for a decorative mark */
  title?: string;
  /** tints the star core with the Sol amber (default: official mono mark) */
  accent?: boolean;
  /** extra classes for the svg — responsive sizing through tailwind */
  className?: string;
};

/** The DevThink logo mark: the two official paths, mono by default. */
export function SolLogoMark({ size = 28, title, accent = false, className = "" }: SolLogoMarkProps) {
  const coreFill = accent ? "var(--sol-sun, #F59E0B)" : "currentColor";
  if (title) {
    return (
      <svg
        viewBox="0 0 800 800"
        width={size}
        height={size}
        className={className}
        fillRule="evenodd"
        clipRule="evenodd"
        shapeRendering="geometricPrecision"
        role="img"
        aria-label={title}
        focusable="false"
      >
        <title>{title}</title>
        <path className="sol-logo__core" fill={coreFill} d={CORE_PATH} />
        <path className="sol-logo__frame" fill="currentColor" d={FRAME_PATH} />
      </svg>
    );
  }
  return (
    <svg
      viewBox="0 0 800 800"
      width={size}
      height={size}
      className={className}
      fillRule="evenodd"
      clipRule="evenodd"
      shapeRendering="geometricPrecision"
      aria-hidden="true"
      focusable="false"
    >
      <path className="sol-logo__core" fill={coreFill} d={CORE_PATH} />
      <path className="sol-logo__frame" fill="currentColor" d={FRAME_PATH} />
    </svg>
  );
}

