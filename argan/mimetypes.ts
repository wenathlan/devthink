/** The row count of the catalog (the number the pane and the tests announce). */
export const MIMETYPE_COUNT = MIMETYPES.length;

/** Finds one catalog row by its media type (case-insensitive, exact match). */
export function findMimeType(type: string): MimeTypeRow | undefined {
  const wanted = type.trim().toLowerCase();
  return MIMETYPES.find((row) => row.type === wanted);
}

/**
 * Resolves the catalog row of one file extension: the first row that claims it in family
 * order wins, so ".ts" answers video/mp2t and ".tsx" answers application/typescript. The
 * leading dot is optional and the lookup is case-insensitive.
 */
export function mimeTypeForExtension(extension: string): MimeTypeRow | undefined {
  const wanted = extension.trim().toLowerCase().replace(/^\./, "");
  if (!wanted) return undefined;
  return MIMETYPES.find((row) => row.extensions.includes(wanted));
}

/** Lists every extension the catalog maps to one media type (empty when unknown). */
export function extensionsForType(type: string): readonly string[] {
  return findMimeType(type)?.extensions ?? [];
}

/** Answers the family of one media type (undefined when the type is not in the catalog). */
export function mimeFamilyOf(type: string): MimeFamily | undefined {
  return findMimeType(type)?.family;
}

/** Lists every row of one family (the pane renders one group per family). */
export function mimetypesByFamily(family: MimeFamily): MimeTypeRow[] {
  return MIMETYPES.filter((row) => row.family === family);
}
