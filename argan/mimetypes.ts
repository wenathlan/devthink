// # mimetypes — the media type catalog of the family, housed at the argan root.
// Library-grade module shipped inside the published packages (npm, maven with the Spring
// Boot rider): it owns the registry rows and pure, generic helpers only — zero consumer
// data. The catalog answers every family the gateway serves — text, image, audio, video,
// application, font, model, chemical, message and multipart — assembled from the IANA
// registry, the freedesktop globs, the node mime-db and the argan canonical pins (the law
// rows: .ts answers video/mp2t, .tsx answers application/typescript). Extension collisions
// resolve in catalog order — the family groups run application, video, audio, image, font,
// model, chemical, message, multipart, text — and the first row claiming an extension
// keeps it, exactly the way the gateway head answers a lookup. The rows ride the literal
// factory below so the three-thousand-row table stays one flat, typeable MimeTypeRow[]
// (a raw literal this wide would fuse into a union the checker refuses to represent).

/** The top-level families of the catalog (the type tree before the slash). */
export type MimeFamily =
  | "application"
  | "video"
  | "audio"
  | "image"
  | "font"
  | "model"
  | "chemical"
  | "message"
  | "multipart"
  | "text";

/** One row of the mimetype catalog served by the gateway mime layer. */
export interface MimeTypeRow {
  /** the media type, lowercase, registered or legacy-canonical ("video/mp2t") */
  type: string;
  /** the file extensions the layer maps to the type, dotless and lowercase (may be empty) */
  extensions: readonly string[];
  /** the top-level family of the type */
  family: MimeFamily;
}

/** Builds one catalog row: the literal factory that keeps the wide table typeable. */
function row(type: string, extensions: readonly string[], family: MimeFamily): MimeTypeRow {
  return { type, extensions, family };
}

